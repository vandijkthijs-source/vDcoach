// Generate the server's deterministic engine from the SAME TypeScript used by the app.
const fs=require('fs'),path=require('path'),ts=require('typescript');
const root=path.join(__dirname,'..'),out=path.join(root,'server','director');fs.mkdirSync(out,{recursive:true});
for(const name of ['model','director','focus-planner','life-planning','widget-model','timer-model']){
 const source=fs.readFileSync(path.join(root,'lib',name+'.ts'),'utf8');
 const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText.replace(/require\("\.\/([^"/]+)"\)/g,'require("./$1.cjs")');
 fs.writeFileSync(path.join(out,name+'.cjs'),'// GENERATED by scripts/build-director.cjs; edit lib/'+name+'.ts\n'+code);
}
